import os
import shutil

import pytest

os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")


def pytest_addoption(parser):
    parser.addoption("--live", action="store_true", help="run tests that download from YouTube")


def pytest_collection_modifyitems(config, items):
    live = config.getoption("--live") or os.environ.get("TUBESNATCH_LIVE") == "1"
    skip_live = pytest.mark.skip(reason="needs --live (talks to YouTube)")
    skip_ff = pytest.mark.skip(reason="ffmpeg not available")
    from tubesnatch import paths

    have_ff = bool(paths.ffmpeg_dir() or shutil.which("ffmpeg"))
    for item in items:
        if "live" in item.keywords and not live:
            item.add_marker(skip_live)
        if "ffmpeg" in item.keywords and not have_ff:
            item.add_marker(skip_ff)


